// Regenerate after adding photos: npm run generate:photos
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const publicDir = path.join(root, "public");
const gallerySourcePath = path.join(root, "src/app/gallery/gallery.ts");
const outputPath = path.join(root, "src/lib/blur-data.ts");

async function collectImages(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const fullPath = path.join(directory, entry.name);
      if (entry.isDirectory()) return collectImages(fullPath);
      if (!/\.(jpe?g|png|webp)$/i.test(entry.name)) return [];
      return [fullPath];
    }),
  );
  return files.flat();
}

const sharp = (await import("sharp")).default;
const files = (await collectImages(publicDir)).sort();
const blurData = {};

for (const file of files) {
  const src = `/${path.relative(publicDir, file).split(path.sep).join("/")}`;
  const buffer = await sharp(file)
    .rotate()
    .resize({ width: 16, withoutEnlargement: true })
    .webp({ quality: 40 })
    .toBuffer();
  blurData[src] = `data:image/webp;base64,${buffer.toString("base64")}`;
}

const gallerySource = await readFile(gallerySourcePath, "utf8");
const referenced = [...gallerySource.matchAll(/src:\s*"([^"]+)"/g)].map(
  (match) => match[1],
);
const missing = referenced.filter((src) => !blurData[src]);
if (missing.length > 0) {
  console.error("Missing image files:\n" + missing.join("\n"));
  process.exit(1);
}

const lines = Object.entries(blurData)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([src, value]) => `  ${JSON.stringify(src)}: ${JSON.stringify(value)},`)
  .join("\n");

const output = `// Generated by scripts/generate-gallery-blurs.mjs. Do not edit by hand.
/* prettier-ignore */
export const blurData: Record<string, string> = {
${lines}
};
`;

await writeFile(outputPath, output);
console.log(`Wrote ${Object.keys(blurData).length} blur placeholders`);
